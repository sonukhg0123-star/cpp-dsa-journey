#include<iostream>
using namespace std;
int main(){
    for(int k=1; k<=4; k++){
        for(int l=1; l<=4; l++){
            cout<<l<<" ";
        }
        cout<<"\n";
    }
    for(int m=1; m<=4; m++){
        for(int n=1; n<=4; n++){
            cout<<m<<" ";
        }
        cout<<"\n";
    }
}